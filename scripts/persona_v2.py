def band_index(ages: np.ndarray) -> np.ndarray:
    """年齢配列 → AGE_BANDS のインデックス(検算・条件付けの共通口)。"""
    los = np.array([b[0] for b in AGE_BANDS])
    return np.clip(np.searchsorted(los, ages, side="right") - 1, 0, len(AGE_BANDS) - 1)


def band_lo(ages: np.ndarray) -> np.ndarray:
    """年齢配列 → 5 歳階級の下限(各種テーブルのキー)。"""
    los = np.array([b[0] for b in AGE_BANDS])
    return los[band_index(ages)]


def resident_age_gender(rng: np.random.Generator, n: int) -> tuple[np.ndarray, list[str]]:
    """住民(L1)の年齢と性別を**同時に**引く(帯 × 性別の 2 次元カテゴリカル)。

    ★v1 の ``np.clip(normal(μ,σ), lo, hi)`` を捨てる = クリップ堆積が原理的に消える。
      (v1 は L4 の N(36,14) を 15 で切って左裾 7.66% を 15 歳 1 点に積み、
       全人口の 4.08% = 40,830 人の人工的な「15 歳」を作っていた。)
    ★年齢と性別を独立に引かない(95-99 歳は 83% が女性)。
    乱数消費 = 2 draw(セル選択 + 帯内一様)。v1 は 1 draw(正規)+ 性別 1 draw。
    """
    cells = []
    for i, (lo, hi, m, f) in enumerate(AGE_BANDS):
        cells.append((i, 0, float(m)))
        cells.append((i, 1, float(f)))
    w = np.array([c[2] for c in cells], float)
    w /= w.sum()
    k = rng.choice(len(cells), size=n, p=w)
    bi = np.array([cells[j][0] for j in k])
    gi = np.array([cells[j][1] for j in k])
    los = np.array([AGE_BANDS[b][0] for b in bi])
    his = np.array([AGE_BANDS[b][1] for b in bi])
    age = los + (rng.random(n) * (his - los + 1)).astype(int)
    gender = ["男" if g == 0 else "女" for g in gi]
    return age.astype(int), gender


def visitor_ages(rng: np.random.Generator, n: int) -> np.ndarray:
    """来街者(L3常連 / L4)の年齢。昼の周辺分布(住民とは別の分布)から。"""
    w = np.array([x[2] for x in VISITOR_AGE_WEIGHTS], float)
    w /= w.sum()
    k = rng.choice(len(VISITOR_AGE_WEIGHTS), size=n, p=w)
    los = np.array([VISITOR_AGE_WEIGHTS[j][0] for j in k])
    his = np.array([VISITOR_AGE_WEIGHTS[j][1] for j in k])
    return (los + (rng.random(n) * (his - los + 1)).astype(int)).astype(int)


def worker_ages(rng: np.random.Generator, n: int) -> np.ndarray:
    """就業者(L2)の年齢。住民の 5 歳階級 × 労働力率 を周辺分布にする
    (= 就業できる年齢しか出ない。v1 の clip(normal(38,11),18,68) を置き換える)。"""
    w = []
    for lo, hi, m, f in AGE_BANDS:
        w.append((m + f) * LABOUR_FORCE_RATE.get(lo, 0.0))
    w = np.array(w, float)
    w /= w.sum()
    k = rng.choice(len(AGE_BANDS), size=n, p=w)
    los = np.array([AGE_BANDS[j][0] for j in k])
    his = np.array([AGE_BANDS[j][1] for j in k])
    age = los + (rng.random(n) * (his - los + 1)).astype(int)
    return np.maximum(age, 15).astype(int)


def sleep_steps_by_age(rng: np.random.Generator, ages: np.ndarray,
                       genders) -> np.ndarray:
    """AGE-B: 年齢 × 性別で条件づけた睡眠長(step)。乱数消費 1 draw(v1 と同数)。"""
    lo = band_lo(np.asarray(ages))
    is_f = np.array([g == "女" for g in genders])
    mins = np.array([SLEEP_MIN_BY_AGE.get(int(x), (440.0, 435.0)) for x in lo])
    center = np.where(is_f, mins[:, 1], mins[:, 0]) / SLEEP_STEP_MIN
    base = np.round(center - SLEEP_SPREAD_STEPS / 2.0).astype(int)
    return np.maximum(24, base + rng.integers(0, SLEEP_SPREAD_STEPS, len(lo)))


def bedtime_by_age(rng: np.random.Generator, ages: np.ndarray) -> np.ndarray:
    """AGE-B: 年齢で条件づけた就寝時刻(分of日)。乱数消費 1 draw(v1 と同数)。"""
    lo = band_lo(np.asarray(ages))
    tbl = np.array([BEDTIME_BY_AGE.get(int(x), (1430, 19)) for x in lo])
    center, width = tbl[:, 0], tbl[:, 1]
    # ★一様乱数 1 本から帯ごとの幅へ写す(整数乱数の剰余で幅を作ると、幅が最大値の
    #   約数でないとき先頭のオフセットに偏りが出る)。
    off = (rng.random(len(lo)) * width).astype(int)
    return ((center + (off - width // 2) * 10) % 1440).astype(int)


def purpose_weights_for_age(base: tuple[tuple[str, float], ...], age: int
                            ) -> tuple[float, ...]:
    """基準の 7 目的重み × 年齢弾性 → 正規化済みの重み(語彙は変えない)。"""
    idx = 0
    for i, e in enumerate(PURPOSE_AGE_EDGES):
        if age >= e:
            idx = i
    w = []
    for name, base_w in base:
        el = PURPOSE_AGE_ELASTICITY.get(name)
        w.append(base_w * (el[idx] if el else 1.0))
    tot = sum(w)
    if tot <= 0:
        return tuple(bw for _n, bw in base)
    return tuple(x / tot for x in w)


def visit_rates(rng: np.random.Generator, n: int) -> np.ndarray:
    """来訪頻度(/日)。混合対数一様 = 「週1〜2回来る層」の裾を作る。

    ★プール規模は据え置いたまま、平均 visit_rate を 0.019 → 約 0.078 に上げる。
      世界が「今日は 13 万人来い」と決めるのではなく、**個々人の来訪習慣が
      現実的になった結果として** 在場が増える(ユーザー原理との整合)。
    乱数消費 = 2 draw(成分選択 + 対数一様)。v1 は 1 draw。
    """
    w = np.array([m[0] for m in VISIT_RATE_MIX], float)
    w /= w.sum()
    k = rng.choice(len(VISIT_RATE_MIX), size=n, p=w)
    lo = np.array([VISIT_RATE_MIX[j][1] for j in k])
    hi = np.array([VISIT_RATE_MIX[j][2] for j in k])
    return np.exp(rng.uniform(np.log(lo), np.log(hi)))


