#: 職長級は**鉱業/建設/製造のみ**(公式定義)。それ以外の業種では非役職へ寄せる。
FOREMAN_INDUSTRIES: frozenset[str] = frozenset({"CN", "MF"})


def size_class(employees: int) -> str:
    """従業者数 → 賃構の企業規模区分。台帳の band 名ではなく実人数から引く
    (band "300+" は 300-999 と 1000+ をまたぐので、名前で引くと誤る)。"""
    n = int(employees or 0)
    if n >= 1000:
        return "1000+"
    if n >= 100:
        return "100-999"
    return "10-99"


#: 賃構 役職第1表の母集団は **事業所規模 10 人以上**(令和2年調査から企業規模 100 人以上
#: 限定は撤廃されたが、10 人未満は依然として母集団外)。9 人以下の社に部長級・課長級を
#: 置くのは分類の誤用なので、**役職ピラミッドは 10 人以上の社にだけ当てる**。
#: 9 人以下の社の「長」は役職ではなく `employment == 役員`(社長・個人事業主)で表現する。
RANK_MIN_EMPLOYEES = 10


def rank_slots(employees: int, industry_key: str, k: int,
               carry: dict | None = None) -> list[str]:
    """その社の k スロットへ役職を決定論で配る(乱数ゼロ)。

    ``carry`` に辞書を渡すと**社をまたいで端数を持ち越す**(Bresenham)。
    これが要る理由: 台帳は 9,872 社の大半が小規模で、社ごとに最大剰余法で丸めると
    最小の重み(部長級 4.60%)が毎回切り捨てられ、**集計値が実数から系統的にずれる**
    (実測: 部長級 3.74% が 0.08% に潰れた)。持ち越すと総和が実比率へ収束する。
    """
    if k <= 0:
        return []
    if int(employees or 0) < RANK_MIN_EMPLOYEES:
        return ["一般"] * k
    w = list(RANK_BY_SIZE[size_class(employees)])
    if str(industry_key or "") not in FOREMAN_INDUSTRIES:
        w[5] += w[3]                      # 職長級 → 非役職へ寄せる(公式定義の業種限定)
        w[3] = 0.0
    tot = sum(w)
    w = [x / tot for x in w]
    if carry is None:
        counts = allocate_slots(tuple(w), k)
    else:
        counts = []
        for i, x in enumerate(w):
            acc = carry.get(i, 0.0) + x * k
            c = int(acc)
            carry[i] = acc - c
            counts.append(c)
        rest = k - sum(counts)
        if rest > 0:                      # 端数の残りは重みの大きい順(=非役職)へ
            order = sorted(range(len(w)), key=lambda i: (-carry.get(i, 0.0), i))
            for i in order[:rest]:
                counts[i] += 1
                carry[i] = max(0.0, carry.get(i, 0.0) - 1.0)
        elif rest < 0:                    # 過剰は非役職から戻す
            for i in (5, 4, 2, 1, 3, 0):
                while rest < 0 and counts[i] > 0:
                    counts[i] -= 1
                    carry[i] = carry.get(i, 0.0) + 1.0
                    rest += 1
    out: list[str] = []
    for name, c in zip(RANK_NAMES, counts):
        out.extend([name] * c)
    return out


